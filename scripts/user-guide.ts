/**
 * The generated pages of the user guide (feature F9 `release-0-1`, PBI `user-guide`): the
 * diagnostics reference from the code registry (`CODES` in `@catspec/core`) and the command
 * reference from `catspec --help`. `npm run guide` writes them; a test fails when they are stale.
 */
import { CODES } from "../packages/core/src/index.js";

import { run } from "../packages/cli/src/index.js";

export const GUIDE_DIR = "docs/spec/catspec-user-guide";
export const DIAGNOSTICS_PAGE = `${GUIDE_DIR}/diagnostics.md`;
export const COMMANDS_PAGE = `${GUIDE_DIR}/commands.md`;

const GENERATED =
  "<!-- Generated by `npm run guide` (scripts/user-guide.ts). Don't edit by hand. -->";

/** The diagnostics reference: one section per registered code, in code order. */
export function diagnosticsPage(): string {
  const codes = Object.entries(CODES).sort(([a], [b]) => (a < b ? -1 : 1));
  const lines = [
    "# Diagnostics reference",
    "",
    GENERATED,
    "",
    "Every diagnostic CatSpec reports has a stable code. The severity is the default; a spec's",
    "status, `enforcement` settings and waivers can change it (see [the spec format](./spec-format.md)).",
    "",
    "| Code | Severity | Title |",
    "|---|---|---|",
    ...codes.map(
      ([code, info]) => `| [${code}](#${code.toLowerCase()}) | ${info.severity} | ${info.title} |`,
    ),
    "",
  ];
  for (const [code, info] of codes) {
    lines.push(`## ${code}`, "", `**${info.title}** · ${info.severity}`, "", info.docs, "");
  }
  return lines.join("\n");
}

/** The output of `catspec <args>`, run in this process at a fixed width. */
async function help(args: string[]): Promise<string> {
  let text = "";
  const write = (chunk: string): boolean => {
    text += chunk;
    return true;
  };
  await run(args, { stdout: { write }, stderr: { write } });
  return text.replace(/\r\n/g, "\n").trimEnd();
}

/** The command names listed under `Commands:` in a help text (`help` itself left out). */
export function commandsIn(helpText: string): string[] {
  const section = helpText.split(/^Commands:\n/m)[1];
  if (section === undefined) return [];
  const names: string[] = [];
  for (const line of section.split("\n")) {
    const match = /^ {2}(\S+)/.exec(line);
    if (!match) {
      if (line.trim() === "") break;
      continue;
    }
    if (match[1] !== "help") names.push(match[1]!);
  }
  return names;
}

/** Every command path of the CLI, depth first: `["check"]`, `["stage", "start"]`, … */
export async function commandPaths(): Promise<string[][]> {
  const paths: string[][] = [];
  const visit = async (path: string[]): Promise<void> => {
    for (const name of commandsIn(await help([...path, "--help"]))) {
      paths.push([...path, name]);
      await visit([...path, name]);
    }
  };
  await visit([]);
  return paths;
}

/** The command reference: the global help, then each command's help. */
export async function commandsPage(): Promise<string> {
  const lines = [
    "# Command reference",
    "",
    GENERATED,
    "",
    "The help of every `catspec` command, as `catspec <command> --help` prints it. Exit codes: `0`",
    "ok or warnings only, `1` errors found, `2` usage or config error, `3` internal error. With",
    "`check --format agent`: `0` done, `2` not done (the agent is blocked), `1` error.",
    "",
    "## catspec",
    "",
    "```text",
    await help(["--help"]),
    "```",
    "",
  ];
  for (const path of await commandPaths()) {
    lines.push(
      `## catspec ${path.join(" ")}`,
      "",
      "```text",
      await help([...path, "--help"]),
      "```",
      "",
    );
  }
  return lines.join("\n");
}
